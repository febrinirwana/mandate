import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const artifactPath = `${root}/contracts/out/MandateAquaApp.sol/MandateAquaApp.json`;
const outputPath = fileURLToPath(new URL("../src/MandateAquaApp.abi.ts", import.meta.url));
const artifact = JSON.parse(await readFile(artifactPath, "utf8"));

if (!Array.isArray(artifact.abi)) {
  throw new Error(`Expected ABI array in ${artifactPath}`);
}

const output = `// Generated by packages/contracts/scripts/generate-mandate-abi.mjs from ${artifactPath}.\nimport type { Abi } from "viem";\n\nexport const mandateAquaAppAbi = ${JSON.stringify(artifact.abi, null, 2)} as const satisfies Abi;\n`;
await writeFile(outputPath, output);
